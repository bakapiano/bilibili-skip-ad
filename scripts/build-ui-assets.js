import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import * as prettier from "prettier";

const root = new URL("../extension/", import.meta.url);
export async function playerAssetsSource() {
  const read = (name) => readFile(new URL(name, root), "utf8");
  const popup = (await read("popup.html")).match(/<main\b[\s\S]*?<\/main>/)[0];
  const icon = await read("icons/icon.svg");
  const assets = {
    html: popup.replace(
      /<img\b[^>]*class="brand-icon"[^>]*>/,
      `<span class="brand-icon">${icon}</span>`,
    ),
    css: [await read("popup.css"), await read("switches.css"), await read("player-panel.css")].join(
      "\n",
    ),
    playerIcon: await read("icons/player-icon.svg"),
    homeIcon: await read("icons/link-home.svg"),
    githubIcon: await read("icons/link-github.svg"),
  };
  for (const name of ["model", "asr", "short", "playback", "pet", "shared", "cache"]) {
    assets[`sectionIcon${name}`] = await read(`icons/section-${name}.svg`);
  }
  const literal = (text) =>
    "`" + text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${") + "`";
  const source = `// Generated by npm run build:ui from shared popup, styles and SVG sources.\n// Checked in so extension/ loads directly; regenerate after editing its source assets.\nglobalThis.BiliSkipPlayerAssets = Object.freeze({\n${Object.entries(
    assets,
  )
    .map(([key, value]) => `${key}: ${literal(value)},`)
    .join("\n")}\n});\n`;
  const config = await prettier.resolveConfig(fileURLToPath(root));
  return prettier.format(source, { ...config, parser: "babel" });
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("player-assets.js", root), await playerAssetsSource(), "utf8");
  console.log("Generated extension/player-assets.js from shared UI assets.");
}
