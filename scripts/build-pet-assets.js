import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createHash } from "node:crypto";
import * as prettier from "prettier";
import { PET_DIALOGUES, MAX_PET_AUDIO_SECONDS } from "../extension/lib/pet-config.js";

const root = new URL("../extension/", import.meta.url);
const defaultsRoot = new URL("../assets/pet/", import.meta.url);
async function defaultAsset(name) {
  const manifest = JSON.parse(await readFile(new URL("manifest.json", defaultsRoot), "utf8"));
  const expected = manifest.files[name];
  assert.ok(expected, `Unknown pet asset: ${name}`);
  const bytes = await readFile(new URL(name, defaultsRoot));
  assert.equal(bytes.length, expected.bytes, `Pet asset size mismatch: ${name}`);
  assert.equal(
    createHash("sha256").update(bytes).digest("hex"),
    expected.sha256,
    `Pet asset hash mismatch: ${name}`,
  );
  return bytes;
}

export async function petAssetsSource({ image, enabled = false, sounds } = {}) {
  const bytes = image || (await defaultAsset("character.png"));
  const audio = sounds || (await Promise.all(["press.mp3", "release.mp3"].map(defaultAsset)));
  assert.ok(bytes.length <= 1024 * 1024, "Preview image must be at most 1 MiB");
  assert.equal(bytes.toString("hex", 0, 8), "89504e470d0a1a0a", "Use a PNG image");
  assert.ok(bytes.readUInt32BE(16) <= 2048 && bytes.readUInt32BE(20) <= 2048);
  const css = await readFile(new URL("pet.css", root), "utf8");
  const bubble = await readFile(new URL("icons/pet-bubble.svg", root), "utf8");
  const assets = {
    enabled,
    image: `data:image/png;base64,${bytes.toString("base64")}`,
    css,
    bubble,
    panelIcon: await readFile(new URL("icons/icon.svg", root), "utf8"),
    dialogues: PET_DIALOGUES,
    sounds: audio.map((bytes) => {
      assert.ok(bytes.length > 0 && bytes.length < 256 * 1024, "Pet sound size is invalid");
      return `data:audio/mpeg;base64,${bytes.toString("base64")}`;
    }),
    soundName: "小黄鸭",
    audioMaxSeconds: MAX_PET_AUDIO_SECONDS,
  };
  const config = await prettier.resolveConfig(fileURLToPath(root));
  return prettier.format(
    `// Generated by scripts/build-pet-assets.js. Asset provenance: PET-ASSETS-NOTICE.md.\nglobalThis.BiliSkipPetAssets = Object.freeze(${JSON.stringify(assets)});\n`,
    { ...config, parser: "babel" },
  );
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("pet-assets.js", root), await petAssetsSource());
  await writeFile(
    new URL("PET-ASSETS-NOTICE.md", root),
    await readFile(new URL("NOTICE.md", defaultsRoot)),
  );
}
